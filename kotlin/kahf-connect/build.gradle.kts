}

// The shared conformance fixtures (SPEC §9) and the shipped catalog, embedded
// into commonTest as generated code so every target reads the same bytes
// with no file system. `-Pkahf.repoRoot=<dir>` points a vendored copy at them.
val repoRoot = providers.gradleProperty("kahf.repoRoot")
    .map { rootProject.file(it) }
    .getOrElse(projectDir.resolve("../.."))
val fixtureFiles = fileTree(repoRoot) {
    include("fixtures/**", "catalog/catalog.json", "catalog/catalog.json.sig", "catalog/model-tiers.json")
}
val generateFixtures by tasks.registering {
    val out = layout.buildDirectory.dir("generated/fixtures/commonTest/kotlin")
    val root = repoRoot
    val files = fixtureFiles
    inputs.files(files)
    outputs.dir(out)
    doLast {
        val entries = files.files
            .map { it.relativeTo(root).invariantSeparatorsPath to Base64.getEncoder().encodeToString(it.readBytes()) }
            .sortedBy { it.first }
        check(entries.any { it.first.startsWith("fixtures/") }) { "no fixtures under $root" }
        val dir = out.get().asFile.resolve("com/kahflabs/connect")
        dir.mkdirs()
        dir.resolve("KahfFixtures.kt").writeText(buildString {
            appendLine("// Generated by :kahf-connect:generateFixtures from the repository's fixtures/. Do not edit.")
            appendLine("package com.kahflabs.connect")
            appendLine()
            appendLine("internal val kahfFixtureFiles: Map<String, String> = mapOf(")
            for ((path, b64) in entries) appendLine("    \"$path\" to \"$b64\",")
            appendLine(")")
        })
    }
}
kotlin.sourceSets.commonTest {
    kotlin.srcDir(generateFixtures)
}
// The live MCP test starts `reference/python/server.py` from the same root.
tasks.named<Test>("jvmTest") {
    systemProperty("kahf.repoRoot", repoRoot.absolutePath)
}

// The ICS tests again with the device in UTC and in two zones that change
// their clocks (kahf-connect#7): floating and all-day times are read in the
// device zone.
val jvmTestTask = tasks.named<Test>("jvmTest")
for ((name, zone) in listOf("Utc" to "UTC", "NewYork" to "America/New_York", "Berlin" to "Europe/Berlin")) {
    val zoned = tasks.register<Test>("jvmIcsTest$name") {
        description = "Runs IcsTest on the JVM with the device zone set to $zone."
        group = "verification"
        testClassesDirs = files(jvmTestTask.map { it.testClassesDirs })
        classpath = files(jvmTestTask.map { it.classpath })
        filter { includeTestsMatching("com.kahflabs.connect.IcsTest") }
        environment("TZ", zone)
        systemProperty("user.timezone", zone)
    }
    tasks.named("check") { dependsOn(zoned) }
}

// Writes ModelTiersTable.kt from catalog/model-tiers.json (port of
// dart/tool/sync_model_tiers.dart), so the SDK carries the table the catalog
// publishes. ModelTiersTest fails if the two ever differ: run
// `./gradlew :kahf-connect:syncModelTiers` after editing the catalog file.
val syncModelTiers by tasks.registering {
    val source = repoRoot.resolve("catalog/model-tiers.json")
    val target = projectDir.resolve("src/commonMain/kotlin/com/kahflabs/connect/ModelTiersTable.kt")
    inputs.file(source)
    outputs.file(target)
    doLast {
        val json = source.readText().trim()
        check("\"\"\"" !in json) { "table contains triple quotes" }
        target.writeText(buildString {
            appendLine("// Generated by :kahf-connect:syncModelTiers from catalog/model-tiers.json.")
            appendLine("// Do not edit: edit the catalog file and run the task.")
            appendLine("package com.kahflabs.connect")
            appendLine()
            appendLine("/** The model-tiers table this SDK was released with. */")
            appendLine("const val bundledModelTiersJson: String = \"\"\"")
            appendLine(json.replace("$", "\${'$'}"))
            appendLine("\"\"\"")
        })
    }
}
